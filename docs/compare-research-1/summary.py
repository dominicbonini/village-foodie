#!/usr/bin/env python3
"""docs/compare-research-1/summary.py — per-country summary of the raw research files (no network, no database).
Writes docs/compare-research-1/summary.md, used by docs/compare-research-1-report.md."""
import json, glob, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
CUR = dict(AU='AUD', HK='HKD', MY='MYR', TH='THB', DK='DKK', PL='PLN', GR='EUR', US='USD', FR='EUR', GB='GBP', BR='BRL', DE='EUR',
           NL='EUR', JP='JPY', IT='EUR', IE='EUR', ES='EUR', NZ='NZD', SG='SGD', CZ='CZK', CA='CAD', AT='EUR', CH='CHF', LI='CHF',
           BE='EUR', LU='EUR', HU='HUF', RO='RON', SE='SEK', NO='NOK', PT='EUR', FI='EUR', HR='EUR', SI='EUR', BG='BGN', EE='EUR',
           LV='EUR', LT='EUR', CY='EUR', MT='EUR', GI='GBP')
ORDER = ['AU', 'HK', 'MY', 'TH', 'DK', 'PL', 'GR', 'US', 'FR', 'GB', 'BR', 'DE', 'NL', 'JP', 'IT', 'IE', 'ES', 'NZ', 'SG', 'CZ', 'CA', 'AT',
         'CH', 'LI', 'BE', 'LU', 'HU', 'RO', 'SE', 'NO', 'PT', 'FI', 'HR', 'SI', 'BG', 'EE', 'LV', 'LT', 'CY', 'MT', 'GI']
FT = ('food_truck', 'street_food_markets', 'pop_up')

rows = collections.defaultdict(list)
for f in sorted(glob.glob(os.path.join(HERE, 'raw', '*.json'))):
    d = json.load(open(f))
    cs = d.get('countries') or [d.get('country')]
    for v in d.get('vendors', []):
        cc = (v.get('country') or cs[0] or '').upper()
        rows[cc].append(v)

def price_txt(p):
    if p.get('price_major') is None: return f"{p.get('plan_name')}: on request"
    per = {'month': '/month', 'year': '/year', 'day': '/day', 'week': '/week', 'one_off': ' one-off'}.get(p.get('period') or 'month', f"/{p.get('period')}")
    fee = f" + {p['per_order_pct']}%" if p.get('per_order_pct') else ''
    return f"{p.get('plan_name')}: {p['price_major']:g} {p.get('currency')}{per}{fee}"

out = ['# compare-research-1 — per-country summary (generated by summary.py from raw/*.json)', '']
tot = collections.Counter()
for cc in ORDER:
    vs = rows.get(cc, [])
    elig = [v for v in vs if v.get('verdict') == 'eligible']
    priced = [v for v in elig if any(isinstance(p.get('price_major'), (int, float)) for p in v.get('plans', []))]
    local = [v for v in priced if any(isinstance(p.get('price_major'), (int, float)) and (p.get('currency') or '').upper() == CUR[cc] for p in v.get('plans', []))]
    ftp = [v for v in priced if v.get('focus') in FT]
    # Dominic's preference: with 2+ priced food-truck tools, only those count; otherwise all eligible priced tools
    counted = [v for v in local if (v.get('focus') in FT) or len([x for x in local if x.get('focus') in FT]) < 2]
    pub = len(counted) >= 2
    tot['countries'] += 1; tot['publishable'] += pub
    out.append(f"## {cc} ({CUR[cc]}) — {len(counted)} eligible with a price in {CUR[cc]} counted → {'**2+ — publishable under the simpler rule**' if pub else '**not yet**'}")
    out.append(f"eligible {len(elig)} · with a price {len(priced)} · in {CUR[cc]} {len(local)} · food-truck tools with a price {len(ftp)}")
    out.append('')
    out.append('| Competitor | Focus | Eligible | Price (own site, today) | Quote / URL |')
    out.append('|---|---|---|---|---|')
    for v in vs:
        e = v.get('eligibility') or {}
        q = (e.get('order_quote') or e.get('food_quote') or v.get('reason') or '').replace('|', '/').replace('\n', ' ')[:120]
        url = e.get('order_url') or e.get('food_url') or v.get('website') or ''
        pr = '; '.join(price_txt(p) for p in v.get('plans', [])[:3]) or '—'
        verdict = {'eligible': 'yes', 'not_relevant': 'no — not relevant', 'unreadable': 'unread'}.get(v.get('verdict'), v.get('verdict'))
        out.append(f"| {v.get('name')} | {v.get('focus') or '-'} | {verdict} | {pr.replace('|', '/')} | «{q}» {url} |")
    out.append('')
out.insert(2, f"**{tot['publishable']} of {tot['countries']} countries researched reach 2+ eligible competitors with a price in their own currency.**\n")
open(os.path.join(HERE, 'summary.md'), 'w').write('\n'.join(out) + '\n')
print(f"{tot['publishable']} of {tot['countries']} publishable; written summary.md")
for cc in ORDER:
    vs = rows.get(cc, [])
    elig = [v for v in vs if v.get('verdict') == 'eligible']
    local = [v for v in elig if any(isinstance(p.get('price_major'), (int, float)) and (p.get('currency') or '').upper() == CUR[cc] for p in v.get('plans', []))]
    ft = [v for v in local if v.get('focus') in FT]
    counted = ft if len(ft) >= 2 else local
    print(cc, len(counted), ', '.join(v['name'][:24] for v in counted))
