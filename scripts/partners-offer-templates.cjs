#!/usr/bin/env node
// scripts/partners-offer-templates.cjs — partners offer (16 November 2026, docs/partners-3-report.md §0): the partner templates
// Dominic approved ("templates approved", with three edits: {{features_url}}; "It's free for {{org}} to take part."; "Thanks for
// reading."), in English and their translations (docs/partners-3/templates/<lang>.json, back-translations inside), into:
//   • lib/partner-offer-phrases.ts — the words around an offer's numbers in each language (lib/partner-template.ts offerValues);
//   • supabase/migrations/20261110_partner_templates.sql — one outreach_templates row per audience × step × language,
//     slug partner-<assoc|dir>-<step>-<lang> (lib/partner-programme.ts templateSlugFor). Inserted only where the slug is not there.
// It refuses a translation whose merge fields, line breaks or ending differ from English. Run by hand:
//   node scripts/partners-offer-templates.cjs
'use strict'
const fs = require('fs')
const path = require('path')
const REPO = path.resolve(__dirname, '..')
const DIR = path.join(REPO, 'docs/partners-3/templates')
const LANGS = ['en', 'fr', 'nl', 'de', 'es', 'it', 'sv']
const STEPS = ['1_first_contact', '2_chase_1', '3_chase_2', '4_final_chase']
const STEP_LABEL = { '1_first_contact': 'First contact', '2_chase_1': 'Chase 1 (+3 days)', '3_chase_2': 'Chase 2 (+7 days)', '4_final_chase': 'Final (+14 days)' }
const AUD_LABEL = { assoc: 'Associations & collectives', dir: 'Directories & media' }
const read = l => JSON.parse(fs.readFileSync(path.join(DIR, `${l}.json`), 'utf8'))
const fields = t => (t.match(/\{\{\s*[a-z_]+(?:\|[^}]*)?\s*\}\}/g) || []).map(f => f.replace(/\|[^}]*/, '')).sort().join(' ')
const en = read('en')
const problems = []
const all = {}
for (const l of LANGS) {
  const d = read(l); all[l] = d
  for (const a of ['assoc', 'dir']) for (const s of STEPS) {
    const t = d.templates?.[a]?.[s], e = en.templates[a][s]
    if (!t) { problems.push(`${l} ${a} ${s}: missing`); continue }
    for (const k of ['subject', 'body']) if (fields(t[k]) !== fields(e[k])) problems.push(`${l} ${a} ${s} ${k}: merge fields differ (${fields(t[k])} vs ${fields(e[k])})`)
    if (!t.body.endsWith('\n\n{{signature}}\n{{opt_out}}')) problems.push(`${l} ${a} ${s}: does not end with the signature and opt-out`)
    if ((t.body.match(/\n\n/g) || []).length !== (e.body.match(/\n\n/g) || []).length) problems.push(`${l} ${a} ${s}: paragraph count differs`)
    if (!/\{\{contact_name\|[^}]+\}\}/.test(t.body)) problems.push(`${l} ${a} ${s}: no contact-name fallback`)
  }
  const ph = d.phrases || {}
  for (const k of ['deal_extra_months', 'deal_percent_off_any', 'deal_percent_off_plan', 'deal_fixed_price']) {
    if (!ph[k] || !ph[k].one || !ph[k].other) problems.push(`${l} phrases.${k}: one / other missing`)
  }
  for (const k of ['commission_two_years', 'commission_one_year', 'contact_fallback']) if (!ph[k]) problems.push(`${l} phrases.${k}: missing`)
  const need = { deal_extra_months: ['{n}'], deal_percent_off_any: ['{pct}', '{months}'], deal_percent_off_plan: ['{pct}', '{plan}', '{months}'], deal_fixed_price: ['{plan}', '{price}', '{months}'] }
  for (const [k, toks] of Object.entries(need)) for (const f of ['one', 'other']) for (const tok of toks) if (ph[k] && !String(ph[k][f]).includes(tok)) problems.push(`${l} phrases.${k}.${f}: no ${tok}`)
  if (ph.commission_two_years && !(ph.commission_two_years.includes('{y1}') && ph.commission_two_years.includes('{y2}'))) problems.push(`${l} commission_two_years: {y1}/{y2}`)
  if (ph.commission_one_year && !ph.commission_one_year.includes('{y1}')) problems.push(`${l} commission_one_year: {y1}`)
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1) }

const phrases = Object.fromEntries(LANGS.map(l => [l, (({ contact_fallback, deal_extra_months, deal_percent_off_any, deal_percent_off_plan, deal_fixed_price, commission_two_years, commission_one_year }) =>
  ({ contact_fallback, deal_extra_months, deal_percent_off_any, deal_percent_off_plan, deal_fixed_price, commission_two_years, commission_one_year }))(all[l].phrases)]))
const ts = fs.readFileSync(path.join(REPO, 'lib/partner-offer-phrases.ts'), 'utf8').replace(/export const PARTNER_PHRASES[\s\S]*$/, '')
fs.writeFileSync(path.join(REPO, 'lib/partner-offer-phrases.ts'), `${ts}export const PARTNER_PHRASES: Record<string, OfferPhrases> = ${JSON.stringify(phrases, null, 2)}\n`)

const q = v => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const sql = [`-- 20261110_partner_templates.sql — the partner programme's email templates (Dominic: "templates approved", 16 November 2026, with
-- his three edits), in ${LANGS.join(', ')}. GENERATED by scripts/partners-offer-templates.cjs from docs/partners-3/templates/<lang>.json
-- (English back-translations in each file and in docs/partners-3-report.md) — do not edit by hand.
-- ${LANGS.length * 8} rows: partner-<assoc|dir>-<step>-<lang>. 🔴 INSERTS ONLY, where the slug is not there yet. serves_kind / serves_lead_type
-- are left null, so no truck sequence slot or rung ever picks one; the truck composer does not list them (ProspectWorkspace).
-- Nothing is sent by this: a partner needs a code (its offer), a verified address, an allowed country and an approved queue.
--
-- Run with: npx -y -p pg@8.13.1 node scripts/db-migrate.cjs supabase/migrations/20261110_partner_templates.sql --approved-by-dominic
set lock_timeout = '3s';
begin;
`]
let order = 900
for (const a of ['assoc', 'dir']) for (const s of STEPS) for (const l of LANGS) {
  const t = all[l].templates[a][s], slug = `partner-${a}-${s}-${l}`
  sql.push(`insert into public.outreach_templates (slug, label, channel, subject, body, sort_order, active)
select ${q(slug)}, ${q(`Partner · ${AUD_LABEL[a]} · ${STEP_LABEL[s]} · ${l.toUpperCase()}`)}, 'email', ${q(t.subject)}, ${q(t.body)}, ${order++}, true
where not exists (select 1 from public.outreach_templates where slug = ${q(slug)});`)
}
sql.push(`\ncommit;\n\n-- VERIFY (read-only):\n-- select count(*) from public.outreach_templates where slug like 'partner-%';  -- ${LANGS.length * 8}\n`)
fs.writeFileSync(path.join(REPO, 'supabase/migrations/20261110_partner_templates.sql'), sql.join('\n'))
console.log(`${LANGS.length} languages · ${LANGS.length * 8} templates → supabase/migrations/20261110_partner_templates.sql · phrases → lib/partner-offer-phrases.ts`)
